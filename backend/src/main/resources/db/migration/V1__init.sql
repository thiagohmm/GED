-- V1__init.sql — schema canonico do GED (multiempresa).
-- Gerado para corresponder coluna a coluna as anotacoes JPA; o Hibernate valida
-- via spring.jpa.hibernate.ddl-auto=validate em todo boot.

CREATE TABLE offices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    enabled BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_offices_name UNIQUE (name)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(60) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(60) NOT NULL,
    office_id BIGINT,
    enabled BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    office_id BIGINT NOT NULL,
    CONSTRAINT uk_projects_office_name UNIQUE (office_id, name)
);

CREATE TABLE folders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    parent_id BIGINT,
    project_id BIGINT,
    assigned_attorney_id BIGINT,
    created_by VARCHAR(60),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folder_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    kind VARCHAR(10) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'EDITANDO',
    current_version INTEGER NOT NULL,
    created_by VARCHAR(60),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_documents_folder_name UNIQUE (folder_id, name)
);

CREATE TABLE document_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    version_number INTEGER NOT NULL,
    file_path VARCHAR(500) NOT NULL,
    size_bytes BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'EDITANDO',
    sha256 VARCHAR(64),
    change_description VARCHAR(500),
    extracted_text TEXT,
    diff_json TEXT,
    uploaded_by VARCHAR(60),
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_document_versions_document_number UNIQUE (document_id, version_number)
);

CREATE TABLE document_status_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    from_status VARCHAR(30) NOT NULL,
    to_status VARCHAR(30) NOT NULL,
    note TEXT,
    changed_by VARCHAR(60),
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE document_tags (
    document_id BIGINT NOT NULL,
    tag_order INTEGER NOT NULL,
    tag VARCHAR(40) NOT NULL,
    PRIMARY KEY (document_id, tag_order)
);

CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    round INTEGER NOT NULL,
    from_version INTEGER NOT NULL,
    to_version INTEGER NOT NULL,
    verdict VARCHAR(25) NOT NULL,
    created_by VARCHAR(60),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_by VARCHAR(60),
    decided_at TIMESTAMP WITH TIME ZONE,
    summary TEXT,
    CONSTRAINT uk_reviews_document_round UNIQUE (document_id, round)
);

CREATE TABLE review_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL,
    author VARCHAR(60) NOT NULL,
    body TEXT NOT NULL,
    diff_line_index INTEGER,
    diff_line_content VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_username VARCHAR(60),
    actor_role VARCHAR(60),
    action VARCHAR(60) NOT NULL,
    resource_type VARCHAR(40),
    resource_id VARCHAR(60),
    detail TEXT,
    ip VARCHAR(64)
);

